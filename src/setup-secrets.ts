const NAME_INDEX = new Map(KNOWN_SECRETS.map((s) => [s.name, s]));

export function getSecretSlot(name: string): SecretSlot | null {
  return NAME_INDEX.get(name as keyof Env) ?? null;
}

/**
 * Snapshot of every known slot + whether it's currently configured.
 * Values themselves are NEVER returned (this endpoint is read-only).
 */
export function listSecretStatus(env: Env): Array<{
  name: string;
  group: SecretGroup;
  label: string;
  hint: string;
  secret: boolean;
  configured: boolean;
  placeholder?: string;
  docsUrl?: string;
  deletable: boolean;
  allowedHost?: string;
}> {
  return KNOWN_SECRETS.map((s) => ({
    name: String(s.name),
    group: s.group,
    label: s.label,
    hint: s.hint,
    secret: s.secret,
    configured: Boolean(env[s.name]),
    placeholder: s.placeholder,
    docsUrl: s.docsUrl,
    deletable: s.deletable !== false,
    allowedHost: s.allowedHost
  }));
}

/**
 * Push a secret to the deployed Worker via the CF API. Caller is
 * responsible for resolving accountId + scriptName before this call.
 */
export async function putWorkerSecret(args: {
  apiToken: string;
  accountId: string;
  scriptName: string;
  name: string;
  value: string;
}): Promise<{ ok: boolean; error?: string }> {
  // Validate the name against our allowlist FIRST so a bad request
  // from the browser can't write arbitrary env vars.
  if (!getSecretSlot(args.name)) {
    return {
      ok: false,
      error: `Unknown secret name "${args.name}". Allowed: ${KNOWN_SECRETS.map((s) => String(s.name)).join(", ")}`
    };
  }
  const r = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${encodeURIComponent(
      args.accountId
    )}/workers/scripts/${encodeURIComponent(args.scriptName)}/secrets`,
    {
      method: "PUT",
      headers: {
        Authorization: `Bearer ${args.apiToken}`,
        "content-type": "application/json"
      },
      body: JSON.stringify({
        name: args.name,
        text: args.value,
        type: "secret_text"
      })
    }
  );
  if (!r.ok) {
    const text = await r.text();
    return { ok: false, error: `cf-api ${r.status}: ${text.slice(0, 300)}` };
  }
  return { ok: true };
}

export async function deleteWorkerSecret(args: {
  apiToken: string;
  accountId: string;
  scriptName: string;
  name: string;
}): Promise<{ ok: boolean; error?: string }> {
  const slot = getSecretSlot(args.name);
  if (!slot) {
    return { ok: false, error: `Unknown secret name "${args.name}"` };
  }
  if (slot.deletable === false) {
    return {
      ok: false,
      error: `Secret "${args.name}" is marked non-deletable. Rotate via PUT instead.`
    };
  }
  const r = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${encodeURIComponent(
      args.accountId
    )}/workers/scripts/${encodeURIComponent(args.scriptName)}/secrets/${encodeURIComponent(args.name)}`,
    {
      method: "DELETE",
      headers: { Authorization: `Bearer ${args.apiToken}` }
    }
  );
  if (!r.ok) {
    const text = await r.text();
    return { ok: false, error: `cf-api ${r.status}: ${text.slice(0, 300)}` };
  }
  return { ok: true };
}

/** Resolve accountId from env, throwing E_BAD_REQUEST if unset. */
export function resolveAccountId(env: Env): string {
  const id = env.CLOUDFLARE_ACCOUNT_ID;
  if (!id) {
    throw new AppError(
      "E_ACCOUNT_ID_MISSING",
      "CLOUDFLARE_ACCOUNT_ID is not set. Run /setup/auto or paste it via the secrets manager.",
      400
    );
  }
  return id;
}
