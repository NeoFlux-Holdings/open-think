/**
 * Secret-management surface for /app#/settings.
 *
 * The /setup/secrets/* endpoints let the user manage Worker secrets from
 * the browser without touching `wrangler secret put`. Under the hood:
 *
 *   PUT    /setup/secrets/<NAME>    — set/update a secret
 *   DELETE /setup/secrets/<NAME>    — drop it
 *   GET    /setup/secrets           — list known slots + current state
 *
 * All writes go through the Cloudflare API using CLOUDFLARE_API_TOKEN.
 * The names of writable secrets are bounded by `KNOWN_SECRETS` so a stolen
 * /app session can't exfiltrate the token by setting weird new keys —
 * we only let you set ones we explicitly recognize.
 */

import type { Env } from "./types";
import { AppError } from "./core/errors";

export type SecretGroup = "auth" | "providers" | "persistence" | "pa-stack" | "cf";

export interface SecretSlot {
  name: keyof Env;
  group: SecretGroup;
  label: string;
  /** Short description shown above the input. */
  hint: string;
  /** Hostname(s) the secret unlocks — surfaced so the user knows where to add to ALLOWED_HOSTS too. */
  allowedHost?: string;
  /** When true, render as a password field (most secrets); false for visible config like model names. */
  secret: boolean;
  /** When set, suggests a sensible default in the placeholder. */
  placeholder?: string;
  /** External link explaining where to find/generate this secret. */
  docsUrl?: string;
  /** When true, allow deletion via DELETE /setup/secrets/<name>. Some
   *  values (HELM_INTERNAL_TOKEN) we'd rather only rotate, not delete. */
  deletable?: boolean;
}

